// 全解読版は1回の生成だと3,000字台で止まってしまうため、前半・後半の2本に分けて並列で書かせる。
// 前半：命式・相性・根本原因・鍵　／　後半：3ヶ月の展開〜最終的な一手・メッセージ
import { userElementLine, partnerElementLine, FACT_RULES, freeSummaryLines } from "./common.js";

function commonHead() {
  return [
    "■出力フォーマット（厳守）",
    "・Markdown記法は禁止（#、##、###、---、>、**、『』以外の引用記号、``` は使わない）。",
    "・見出しは「■」で統一する。箇条書きは「・」で統一する（ハイフン - は使わない）。",
    "・空行は段落の切れ目にのみ使用する。",
    "・口調は終始「占いばあや」（丁寧語に「〜ですわ」「〜わよ」を混ぜる）。上から目線禁止。",
    "・説明文（教科書的）にしない。「この配置だから、貴方は〇〇になりやすいのですわ」と話しかける調子で、感情や行動への影響を優先する。",
    "・相手の心理は複数の層を示す（好き／嫌いの一本化禁止）。",
    "・各章は、指定の文字数を下回らないこと。短くまとめすぎないで、場面や気持ちの動きを具体的に描く。",
  ];
}

function inputs(intake) {
  const p = intake.partner || {};
  const c = intake.concern || {};
  const d = intake.derived || {};
  return [
    ...FACT_RULES,
    ...freeSummaryLines(d),
    "",
    "■入力（材料）",
    userElementLine(d.user_elements),
    partnerElementLine(d.partner_elements),
    "",
    "本人ミニ鑑定：",
    d.user_mini_reading ?? "",
    "",
    "相手ミニ鑑定：",
    d.partner_mini_reading ?? "",
    "",
    `関係性：${p.relation ?? "不明"}`,
    `直近の出来事：${p.recent_event ?? "不明"}`,
    "",
    "悩み（長文）：",
    c.free_text ?? "",
  ];
}

