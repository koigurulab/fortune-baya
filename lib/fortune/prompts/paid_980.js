// /lib/fortune/prompts/paid_980.js
// 実践版は1回の生成だと3,000字前後で止まり480円版と量が変わらないため、前半・後半の2本に分けて並列で書かせる。
// 前半：相性の深掘り・1ヶ月の運勢　／　後半：本音のタイミング〜まとめ
import { userElementLine, partnerElementLine, FACT_RULES, freeSummaryLines } from "./common.js";

function commonHead() {
  return [
    "■出力フォーマット（厳守）",
    "・Markdown記法は禁止（#、##、###、---、>、**、『』以外の引用記号、``` は使わない）。",
    "・見出しは「■」で統一する。箇条書きは「・」で統一する（ハイフン - は使わない）。",
    "・空行は段落の切れ目にのみ使用する。",
    "・口調は終始「占いばあや」（丁寧語に「〜ですわ」「〜わよ」を混ぜる）。上から目線禁止。",
    "・五行は説明しない。比喩として軽く触れる。占いとしての語りを優先し、説明文（教科書）にしない。",
    "・断言は避けるが、現実的な見立ては必ず出す（期待だけで濁さない）。",
    "・相手の心理は「好き/嫌い」一本化禁止。「怖さ/迷い/生活の波/余白」を必ず混ぜる。",
    "・区切り線（---）や強調（太字/引用/括弧の多用）は禁止。",
    "・各章は、指定の文字数を下回らないこと。短くまとめすぎないで、場面や気持ちの動きを具体的に描く。",
  ];
}

function inputs(intake) {
  const p = intake.partner || {};
  const c = intake.concern || {};
  const d = intake.derived || {};
  return [
    ...FACT_RULES,
    ...freeSummaryLines(d),
    "",
    "■入力（材料）",
    userElementLine(d.user_elements),
    partnerElementLine(d.partner_elements),
    "",
    "本人ミニ鑑定：",
    d.user_mini_reading ?? "",
    "",
    "相手ミニ鑑定：",
    d.partner_mini_reading ?? "",
    "",
    `関係性：${p.relation ?? "不明"}`,
    `直近の出来事：${p.recent_event ?? "不明"}`,
    "",
    "悩み（長文）：",
    c.free_text ?? "",
  ];
}

function partA() {
  return [
    "【980円版（実践版）の前半】",
    "これは実践版の前半です。後半（本音のタイミング・分岐点・一手・落とし穴・まとめ）は別に書くので、ここでは書かない。締めの挨拶や祈りも書かない。",
    "",
    "■文字数：日本語で2500〜3000字",
    "",
    "■構成（この順番・この見出し）",
    "・1行目に「鑑定結果（実践版）」（■は付けない）",
    "・冒頭2段落：1段落目は貴方とお相手の気質を2文で。2段落目は今回の状況（入力に書かれていること）を1〜2文で要約し「ここから占いますね」でつなぐ。",
    "■相性の深掘り（1000〜1300字）",
    "■1ヶ月の運勢（第1週〜第4週、各週350〜450字。「第1週：」のように通常文で書き、見出しにしない）",
    "",
    "■書き方",
    "・ありがちな心の動きを、貴方側・お相手側それぞれ3つ以上、自然に散らす。",
    "・週ごとに、気持ちの動き・起きやすい出来事・気をつけることを具体的に。",
  ];
}

function partB() {
  return [
    "【980円版（実践版）の後半】",
    "これは実践版の後半です。前半（相性の深掘り・1ヶ月の運勢）は別に書いてあるので繰り返さない。タイトル行や前置きは書かず、最初の見出しから始める。",
    "",
    "■文字数：日本語で2800〜3300字",
    "",
    "■構成（この順番・この見出し）",
    "■相手の本音が出やすいタイミング（3パターン、各250〜300字。いつ頃・どんな場面・どんなサインか）",
    "■分岐点と見極めサイン（2つ、各350〜450字）",
    "■具体的な一手と送る文面（一手は1つだけ。なぜ効くか・送るタイミング・そのまま使える文面1つ。合わせて500〜600字）",
    "■避けるべき落とし穴（3つ、各150〜200字）",
    "■吉・凶・一手（各1行）",
    "■まとめ（4〜7文）",
    "",
    "■無料鑑定との整合",
    "・無料鑑定で伏せた一手が渡されている時は、具体的な一手をそれと同じ向きにする。吉・凶も無料鑑定と同じ向きにする。",
    "",
    "■まとめの要件",
    "・1ヶ月の流れを一言で言い換える（例：静まってから動く月）。",
    "・選べる余地を残す（追う/待つ/区切るの全否定をしない）。ただし結論はぼかさない。",
    "・最後は3行以内で静かに締める（長い説教禁止）。",
    "・締めの例：貴方の縁が静かに整いますように。占いばあやは、いつでも貴方の幸せを願っていますわ。",
  ];
}

// part: "A"（前半）| "B"（後半）
export function promptPaid980(intake, part = "A") {
  const body = part === "B" ? partB() : partA();
  return [...body, "", ...commonHead(), "", ...inputs(intake)].join("\n");
}
